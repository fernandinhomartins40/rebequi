import assert from 'node:assert/strict';

export function validateCommercialConsistency(db) {
  const result = db(`
    const assert = (await import('node:assert/strict')).default;
    const {randomUUID} = await import('node:crypto');
    const {SaleRepository} = await import('./apps/backend/dist/repositories/sale.repository.js');
    const {runIntegrationJobs} = await import('./apps/backend/dist/services/integration-outbox.service.js');
    const category = await prisma.category.findFirstOrThrow();
    const key = randomUUID();
    const p = await prisma.product.create({data:{name:'Concurrency validation',slug:key,price:10,stock:1,categoryId:category.id}});
    const repo = new SaleRepository();
    const orders = [];
    let channel;
    try {
      channel = await prisma.channel.create({data:{type:'MANUAL',name:'Integration validation '+key}});
      await prisma.channelListing.create({data:{channelId:channel.id,productId:p.id,syncStatus:'SYNCED'}});
      const create = () => repo.createSaleWithStock({sale:{referenceCode:randomUUID(),status:'PAID',paymentMethod:'PIX',subtotal:10,total:10,items:{create:[{productId:p.id,productNameSnapshot:p.name,quantity:1,unitPrice:10}]}},stockDecrements:[{productId:p.id,quantity:1,stockBefore:999,reason:'validation'}]});
      const concurrent = await Promise.allSettled([create(),create()]);
      assert.equal(concurrent.filter(r=>r.status==='fulfilled').length,1);
      assert.equal((await prisma.product.findUniqueOrThrow({where:{id:p.id}})).stock,0);
      assert.equal(await prisma.saleItem.count({where:{productId:p.id}}),1);
      const sale = concurrent.find(r=>r.status==='fulfilled').value;
      const movement = await prisma.stockMovement.findFirstOrThrow({where:{productId:p.id,type:'SALE'}});
      assert.equal(movement.stockBefore,1); assert.equal(movement.stockAfter,0);
      assert.equal((await prisma.channelListing.findFirstOrThrow({where:{productId:p.id}})).syncStatus,'OUT_OF_SYNC');
      assert.equal(await prisma.integrationJob.count({where:{productId:p.id}}),1);
      await Promise.all([repo.transitionStatus(sale.id,'CANCELED'),repo.transitionStatus(sale.id,'CANCELED')]);
      assert.equal((await prisma.product.findUniqueOrThrow({where:{id:p.id}})).stock,1);
      assert.equal(await prisma.stockMovement.count({where:{productId:p.id,type:'RETURN'}}),1);
      await assert.rejects(()=>repo.transitionStatus(sale.id,'PAID'));
      const pending = await prisma.integrationJob.findFirstOrThrow({where:{productId:p.id}});
      await prisma.integrationJob.update({where:{id:pending.id},data:{status:'RUNNING',leaseToken:'expired-worker',leaseUntil:new Date(0)}});
      await runIntegrationJobs();
      assert.equal(await prisma.integrationJob.count({where:{productId:p.id,status:'COMPLETED'}}),2);
      await runIntegrationJobs();
      assert.equal((await prisma.product.findUniqueOrThrow({where:{id:p.id}})).stock,1);
      const {reserveOrderStock,expireStockReservations}=await import('./apps/backend/dist/services/stock-reservation.service.js');
      const {SaleService}=await import('./apps/backend/dist/services/sale.service.js');
      const {OrderRepository}=await import('./apps/backend/dist/repositories/order.repository.js');
      const customer=await prisma.user.findFirstOrThrow({where:{role:'CUSTOMER'}});
      for(let i=0;i<3;i++) orders.push(await prisma.customerOrder.create({data:{referenceCode:randomUUID(),userId:customer.id,customerNameSnapshot:'Reservation validation',customerWhatsapp:'11900000000',items:{create:{productId:p.id,productNameSnapshot:p.name,productSlugSnapshot:p.slug,quantity:1,unitPrice:10}}}}));
      const reservations=await Promise.allSettled(orders.slice(0,2).map(o=>reserveOrderStock(o.id)));
      assert.equal(reservations.filter(r=>r.status==='fulfilled').length,1);
      const reservedOrder=orders[reservations.findIndex(r=>r.status==='fulfilled')];
      assert.equal((await prisma.product.findUniqueOrThrow({where:{id:p.id}})).reservedStock,1);
      assert.equal((await prisma.product.findUniqueOrThrow({where:{id:p.id}})).stock,1);
      await reserveOrderStock(reservedOrder.id);
      await assert.rejects(create);
      const service=new SaleService();
      const input={orderId:reservedOrder.id,paymentMethod:'PIX',status:'PAID',idempotencyKey:randomUUID()};
      const repeated=await Promise.all([service.createSale(undefined,input),service.createSale(undefined,input)]);
      assert.equal(repeated[0].id,repeated[1].id);
      await assert.rejects(()=>service.createSale(undefined,{...input,discount:1}));
      assert.equal((await prisma.product.findUniqueOrThrow({where:{id:p.id}})).reservedStock,0);
      assert.equal((await prisma.product.findUniqueOrThrow({where:{id:p.id}})).stock,0);
      await assert.rejects(()=>new OrderRepository().updateOrder(reservedOrder.id,{status:'CANCELED'}));
      await repo.transitionStatus(repeated[0].id,'CANCELED');
      await reserveOrderStock(orders[2].id);
      await prisma.stockReservation.updateMany({where:{orderId:orders[2].id},data:{expiresAt:new Date(0)}});
      await expireStockReservations(); await expireStockReservations();
      assert.equal((await prisma.product.findUniqueOrThrow({where:{id:p.id}})).reservedStock,0);
      assert.equal((await prisma.product.findUniqueOrThrow({where:{id:p.id}})).stock,1);
      await reserveOrderStock(orders[2].id);
      await new OrderRepository().updateOrder(orders[2].id,{status:'CANCELED'});
      assert.equal((await prisma.product.findUniqueOrThrow({where:{id:p.id}})).reservedStock,0);
      const {getIntegrationOperations,retryIntegrationJob}=await import('./apps/backend/dist/services/integration-operations.service.js');
      const failedJob=await prisma.integrationJob.findFirstOrThrow({where:{productId:p.id,status:'PENDING'}});
      await prisma.integrationJob.update({where:{id:failedJob.id},data:{status:'FAILED',attempts:5,lastError:'private-provider-body'}});
      const operations=await getIntegrationOperations();
      assert.ok(operations.failed.some(job=>job.id===failedJob.id));
      assert.ok(!JSON.stringify(operations).includes('private-provider-body'));
      await retryIntegrationJob(failedJob.id,customer.id);
      await assert.rejects(()=>retryIntegrationJob(failedJob.id,customer.id));
      assert.equal(await prisma.integrationAudit.count({where:{jobId:failedJob.id}}),1);
      await runIntegrationJobs();
      assert.equal((await prisma.integrationJob.findUniqueOrThrow({where:{id:failedJob.id}})).status,'COMPLETED');
      const {getChannelAdapter}=await import('./apps/backend/dist/services/channels/index.js');
      for(const provider of ['SHOPEE','AMAZON','MAGALU','CASAS_BAHIA','AMERICANAS','SHEIN']) assert.equal((await getChannelAdapter(provider).testConnection({})).ok,false);
      const {ChannelService}=await import('./apps/backend/dist/services/channel.service.js');
      await new ChannelService().deleteChannel(channel.id);
      assert.equal((await prisma.channel.findUniqueOrThrow({where:{id:channel.id}})).isActive,false);
      assert.equal(await prisma.channelListing.count({where:{channelId:channel.id}}),1);
      const {encryptSecret}=await import('./apps/backend/dist/utils/crypto.util.js');
      await prisma.channel.update({where:{id:channel.id},data:{type:'MERCADO_LIVRE',isActive:true,credentials:encryptSecret(JSON.stringify({clientId:'integration-app',clientSecret:'integration-secret'}))}});
      const {beginMercadoLivreAuthorization,finishMercadoLivreAuthorization}=await import('./apps/backend/dist/services/channels/mercado-livre-auth.service.js');
      const started=await beginMercadoLivreAuthorization(channel.id,'integration-user');
      const authUrl=new URL(started.url); assert.equal(authUrl.hostname,'auth.mercadolivre.com.br');
      assert.ok(authUrl.searchParams.get('code_challenge')); assert.ok(!started.url.includes('integration-secret'));
      const state=authUrl.searchParams.get('state');
      await assert.rejects(()=>finishMercadoLivreAuthorization(state,'integration-code','different-user'));
      const oldFetch=globalThis.fetch;
      globalThis.fetch=async(url)=>url.endsWith('/oauth/token')?new Response(JSON.stringify({access_token:'integration-token',refresh_token:'integration-refresh',expires_in:3600,user_id:1234,scope:'read'})):new Response(JSON.stringify({id:1234,site_id:'MLB'}));
      try {
        assert.equal(await finishMercadoLivreAuthorization(state,'integration-code','integration-user'),channel.id);
        await assert.rejects(()=>finishMercadoLivreAuthorization(state,'integration-code','integration-user'));
        const connected=await prisma.channel.findUniqueOrThrow({where:{id:channel.id}});
        assert.equal(connected.status,'CONNECTED'); assert.ok(!connected.credentials.includes('integration-token'));
      } finally {globalThis.fetch=oldFetch;}
      console.log('COMMERCIAL_CONSISTENCY_OK');
    } finally {
      const jobs=await prisma.integrationJob.findMany({where:{productId:p.id},select:{id:true}});
      await prisma.integrationAudit.deleteMany({where:{jobId:{in:jobs.map(job=>job.id)}}});
      await prisma.integrationJob.deleteMany({where:{productId:p.id}});
      const items=await prisma.saleItem.findMany({where:{productId:p.id},select:{saleId:true}});
      await prisma.stockMovement.deleteMany({where:{productId:p.id}});
      await prisma.sale.deleteMany({where:{id:{in:items.map(i=>i.saleId)}}});
      await prisma.customerOrder.deleteMany({where:{id:{in:orders.map(o=>o.id)}}});
      if(channel) await prisma.channel.delete({where:{id:channel.id}});
      await prisma.product.delete({where:{id:p.id}});
    }
  `);
  assert.ok(result.includes('COMMERCIAL_CONSISTENCY_OK'), result);
}
